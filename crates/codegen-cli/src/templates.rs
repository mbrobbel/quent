#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fill_replaces_all_occurrences() {
        let out = fill(
            PY_CARGO,
            &[("__INSTR_PKG__", "foo-instr"), ("__MODULE__", "foo")],
        );
        assert_eq!(out.matches("foo-instr").count(), 2);
        assert!(out.contains("name = \"foo\""));
        // The empty workspace table must always be present.
        assert!(out.contains("[workspace]\n"));
    }
}
