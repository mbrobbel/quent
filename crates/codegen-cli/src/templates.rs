//! Source templates for generated scaffold crates.
//!
//! Placeholders use the `__TOKEN__` form and are substituted via [`fill`].
//! Each generated `Cargo.toml` carries an explicit empty `[workspace]` table so
//! cargo treats it as its own workspace root and does not attach it to (or get
//! captured by) an ancestor workspace.

/// Replace every `(token, value)` pair in `template` (all occurrences).
pub fn fill(template: &str, pairs: &[(&str, &str)]) -> String {
    let mut out = template.to_string();
    for (token, value) in pairs {
        out = out.replace(token, value);
    }
    out
}

